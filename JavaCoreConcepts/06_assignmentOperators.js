let x=10;
x=x+10;
console.log(x); // 20
x+=10; // equivalent to x = x + 10
console.log(x); // 30

let y=5;
y-=2;   // equivalent to y = y - 2
console.log(y); // 3
y*=3;   // equivalent to y = y * 3
console.log(y); // 9
y/=3;   // equivalent to y = y / 3
console.log(y); // 3
y%=2;   // equivalent to y = y % 2
console.log(y); // 1
y**=3;  // equivalent to y = y ** 3 (1 raised to the power of 3)
console.log(y); // 1

