let a=10, b=5;
console.log(a);
console.log(b);
console.log(a+b);
console.log(a-b);
console.log(a*b);
console.log(a/b);
console.log(a%b);
console.log(a**b); // exponentiation
console.log(a++); // post-increment: returns a, then increments a
console.log(a); // now a is 11
console.log(++b); // pre-increment: increments b, then returns b (6)    
console.log(b); // b is still 6
console.log(a--); // post-decrement: returns a, then decrements a
console.log(a); // now a is 10
console.log(--b);   // pre-decrement: decrements b, then returns b (5)
console.log(b); // b is still 5 

