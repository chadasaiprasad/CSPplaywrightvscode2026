let browser= "chrome";
switch (browser){
    case "chrome":
        console.log("you are using chrome");
        break;
    case "firefox":
        console.log("you are using firefox");
        break;
    case "safari":
        console.log("you are using safari");
        break;
    case "edge":
        console.log("you are using edge");
        break;
    default:
        console.log("unknown browser");
}